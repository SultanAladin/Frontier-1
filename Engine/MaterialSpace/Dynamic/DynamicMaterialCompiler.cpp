#include "Engine/MaterialSpace/Dynamic/DynamicMaterialCompiler.h"

#include <sstream>

namespace Frontier::MaterialSpace::Dynamic
{

CompiledMaterialSequence CompileMaterialLayerStack(const DynamicMaterialRecipe& Recipe)
{
    CompiledMaterialSequence Compiled {};
    Compiled.StructuralHash = Recipe.LayerStack.ComputeStructuralSignatureHash();
    Compiled.RequiresTransm = Recipe.TransparentSurface;

    std::ostringstream Slang;
    Slang << "// Auto-generated by Frontier DynamicMaterialCompiler (Signature 0x"
          << std::hex << Compiled.StructuralHash << std::dec << ")\n";
    Slang << "void ApplyCompiledLayerSequence(inout ResolvedDynamicSample Sample, const GpuDynamicParameterBlock Params, float3 NormPos, float3 WorldNormal, float3 ViewDir)\n{\n";

    for (std::size_t Index = 0u; Index < Recipe.LayerStack.Layers.size(); ++Index)
    {
        if (!Recipe.LayerStack.QueryLayerEffectiveVisibility(Index))
        {
            continue;
        }
        const auto& Entry = Recipe.LayerStack.Layers[Index];

        MaterialInstructionOp Op {};
        Op.Category         = Entry.Category;
        Op.FieldPattern     = Entry.FieldPattern;
        Op.MaskMode         = Entry.MaskMode;
        Op.ChannelMask      = Entry.ChannelMask;
        Op.SourceLayerIndex = static_cast<uint32_t>(Index);
        Compiled.Instructions.push_back(Op);

        if (Entry.MaskMode == MaskModifierMode::VoxelClockCutoutMask ||
            Entry.FieldPattern == ProceduralFieldPattern::CubicVoxelLattice)
        {
            Compiled.RequiresAlphaCut = true;
        }

        Slang << "    // Layer[" << Index << "]: " << QueryLayerCategoryLabel(Entry.Category)
              << " (" << Entry.LayerTitle << ")\n";
        Slang << "    ApplyDynamicLayerStep(Sample, Params, "
              << static_cast<uint32_t>(Entry.Category) << "u, "
              << static_cast<uint32_t>(Entry.FieldPattern) << "u, "
              << static_cast<uint32_t>(Entry.MaskMode) << "u, "
              << Entry.ChannelMask << "u, NormPos, WorldNormal, ViewDir);\n";
    }

    Slang << "}\n";
    Compiled.GeneratedSlang = Slang.str();
    return Compiled;
}

} // namespace Frontier::MaterialSpace::Dynamic
