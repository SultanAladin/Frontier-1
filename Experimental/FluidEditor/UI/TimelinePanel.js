// 🧩 Timeline dock under the viewport (Fluid layer stack plan §5.1, phase 4):
//
//   ⏮ ◀ ▶ ▸ ⏭  ◆‹ ›◆   00:03.25 / 00:08.00 @ 60 Hz   End [8] s  ⟲ Loop   ● Auto-key   Checkpoints ▮▮▮▯ 3/32   [Dope sheet] [Curves]
//   ┌ tree ─────────────────────┬ ruler 0s 1s 2s … (checkpoint ticks) ──────────────────────────────────────────────┐
//   │ ▾ Campfire · gas volume    │ ◆      ◆                                                                          │
//   │     Buoyancy › Buoyancy    │ ◆──────◆                                                                          │
//   │ ▾ Ground Charge · emitter  │                                                                                   │
//   │     Weight (timing)        │   ◇ ◇  ◇ ◇      ← generated by Start / Duration / Fade; dragging one makes real keys │
//   └───────────────────────────┴──────────────────────── ▲ playhead ─────────────────────────────────────────────────┘
//
// Dope sheet: click a key to select (Shift adds), drag to move (snaps to the step; Alt = free), Ctrl/⌘-drag scales about the playhead,
// Delete removes. Curves: the focused track as a curve; drag keys in time and amount, drag Bezier handles to set tangents.
// Clicking or dragging on the ruler or an empty lane scrubs (the simulation steps forward or restores a checkpoint and re-steps).

import { EaseCodes, ExtrapolationCodes, sampleTrack, findTrack } from '../Engine/KeyTracks.js';
import { LayerSpecificationByCode } from '../Engine/LayerStack.js';
import { ForceTypeById } from '../Engine/ForceGeneratorCatalog.js';

function element(tag, className, html)
{
    const node = document.createElement(tag);
    if (className) node.className = className;
    if (html !== undefined) node.innerHTML = html;
    return node;
}

/** mm:ss.cc */
export function formatTimecode(seconds)
{
    const total = Math.max(0, seconds);
    const minutes = Math.floor(total / 60);
    const rest = total - minutes * 60;
    return `${String(minutes).padStart(2, '0')}:${rest.toFixed(2).padStart(5, '0')}`;
}

const LabelWidth = 220;
const SvgNamespace = 'http://www.w3.org/2000/svg';

export function mountTimeline({ app, host })
{
    const state = { view: 'dope', collapsed: new Set(), selection: [], focus: null, drag: null, open: true, rows: [] };
    host.tabIndex = 0;

    //------------------------------------------------------------------------------------------------------------------------
    //                                                  ROW MODEL
    //------------------------------------------------------------------------------------------------------------------------

    function layerLabel(stack, token, name)
    {
        const layer = stack && stack.Layers.find((candidate) => candidate.Token === token);
        const specification = layer && LayerSpecificationByCode[layer.Category];
        if (!specification) return `${token} › ${name}`;
        const parameter = specification.Parameter.find((candidate) => candidate.Name === name);
        return `${specification.Name} › ${parameter ? parameter.Label : name}`;
    }

    /** Groups (volume → owner) with one row per track; derived Weight tracks (timing fields) are shown hollow. */
    function buildGroups()
    {
        const scene = app.scene;
        const entries = app.allTracks(true);
        const groups = [];
        const gasRows = entries.filter((entry) => entry.Stack === scene.GasStack && !entry.Node);
        if (gasRows.length) groups.push({ Id: 'gas', Title: `${scene.Name}`, Subtitle: 'gas volume', Rows: gasRows.map((entry) => ({ ...entry, Label: layerLabel(entry.Stack, entry.Target.Token, entry.Target.Name) })) });
        for (const node of [...scene.Emitters, ...scene.Forces, ...scene.Particles])
        {
            const rows = entries.filter((entry) => entry.Node === node).map((entry) => ({
                ...entry,
                Owner: node.Name,
                Label: entry.Target.Kind === 'Layer' ? layerLabel(entry.Stack, entry.Target.Token, entry.Target.Name) : entry.Target.Name === 'Weight' ? (entry.Derived ? 'Weight (timing)' : 'Weight') : entry.Target.Name,
            }));
            if (!rows.length) continue;
            const kind = node.Kind === 'Force' ? (ForceTypeById[node.Type] || {}).Name || 'force' : node.Kind === 'Emitter' ? 'emitter' : 'particles';
            groups.push({ Id: node.Id, Title: node.Name, Subtitle: kind.toLowerCase(), Node: node, Rows: rows });
        }
        return groups;
    }

    const rowKey = (row) => `${row.Target.Kind}:${row.Target.Token || row.Target.Id}:${row.Target.Name}`;
    const isSelected = (track, key) => state.selection.some((entry) => entry.Track === track && entry.Key === key);

    //------------------------------------------------------------------------------------------------------------------------
    //                                                  GEOMETRY
    //------------------------------------------------------------------------------------------------------------------------

    function span() { return Math.max(app.timeline().End, 0.5); }
    function laneRect() { const lane = host.querySelector('.tl-ruler'); return lane ? lane.getBoundingClientRect() : { left: 0, width: 1 }; }
    function timeAtClientX(clientX) { const rect = laneRect(); return Math.max(0, ((clientX - rect.left) / Math.max(1, rect.width)) * span()); }
    function percent(time) { return `${(time / span()) * 100}%`; }
    function snap(time, free) { const step = app.stepDeltaTime(); return free ? time : Math.round(time / step) * step; }

    //------------------------------------------------------------------------------------------------------------------------
    //                                                  RENDER
    //------------------------------------------------------------------------------------------------------------------------

    function render()
    {
        if (!app.scene) return;
        host.innerHTML = '';
        host.classList.toggle('collapsed', !state.open);
        host.appendChild(renderBar());
        if (!state.open) return;
        const groups = buildGroups();
        state.rows = groups.flatMap((group) => group.Rows);
        // Keep the selection to keys that still exist (an edit may have replaced a track).
        state.selection = state.selection.filter(({ Track, Key }) => Track.Keys.includes(Key) && state.rows.some((row) => row.Track === Track));
        if (!state.focus || !state.rows.some((row) => rowKey(row) === state.focus)) state.focus = state.rows[0] ? rowKey(state.rows[0]) : null;
        const body = element('div', 'tl-body');
        body.style.setProperty('--tl-label', `${LabelWidth}px`);
        body.appendChild(renderRuler());
        if (state.view === 'dope') body.appendChild(renderDopeSheet(groups));
        else body.appendChild(renderCurves());
        body.appendChild(element('div', 'tl-playhead'));
        host.appendChild(body);
        update();
    }

    function button(label, title, onClick, className = '')
    {
        const node = element('button', className, label);
        node.title = title;
        node.setAttribute('aria-label', title);
        node.addEventListener('click', (event) => { event.stopPropagation(); onClick(); });
        return node;
    }

    function renderBar()
    {
        const bar = element('div', 'tl-bar');
        const timeline = app.timeline();
        const transport = element('div', 'tl-transport');
        transport.append(
            button('<svg width="12" height="12" viewBox="0 0 12 12" aria-hidden="true"><rect x="1.5" y="2" width="1.6" height="8" fill="currentColor"/><path d="M10.5 2v8L4 6z" fill="currentColor"/></svg>', 'Go to start (Home)', () => app.goToStart()),
            button('◀', 'Back one step (,)', () => app.stepBack()),
            button(app.playing ? '❚❚' : '▶', app.playing ? 'Pause (Space)' : 'Play (Space)', () => app.togglePlay(), 'primary'),
            button('▸', 'Forward one step (.)', () => app.stepOnce()),
            button('<svg width="12" height="12" viewBox="0 0 12 12" aria-hidden="true"><rect x="8.9" y="2" width="1.6" height="8" fill="currentColor"/><path d="M1.5 2v8L8 6z" fill="currentColor"/></svg>', 'Go to end (End)', () => app.goToEnd()),
            button('◆‹', 'Previous key', () => { const time = app.adjacentKeyTime(-1); if (time !== null) app.seek(time); }),
            button('›◆', 'Next key', () => { const time = app.adjacentKeyTime(1); if (time !== null) app.seek(time); }),
        );
        bar.appendChild(transport);
        const readout = element('div', 'tl-readout', `<strong id="timeline-time">00:00.00</strong><span> / ${formatTimecode(timeline.End)}</span>`);
        readout.title = `Simulation clock; one step = 1/${Math.round(1 / app.stepDeltaTime())} s (keys snap to it)`;
        bar.appendChild(readout);
        const end = element('label', 'tl-end', '<span>End</span>');
        const endInput = document.createElement('input');
        endInput.type = 'number'; endInput.min = '0.5'; endInput.step = '0.5'; endInput.value = String(timeline.End);
        endInput.addEventListener('change', () => app.setTimeline('End', Number(endInput.value)));
        end.append(endInput, element('span', '', 's'));
        bar.appendChild(end);
        bar.appendChild(button(`⟲ Loop`, timeline.Loop ? 'Loop on: the playhead wraps at End' : 'Loop off: play continues past End', () => app.setTimeline('Loop', !timeline.Loop), timeline.Loop ? 'toggle on' : 'toggle'));
        bar.appendChild(button(`<span class="tl-rec"></span>Auto-key`, app.autoKey ? 'Auto-key on: every edit writes a key at the playhead' : 'Auto-key off: edits change static amounts (keyed parameters still take keys)', () => app.toggleAutoKey(), app.autoKey ? 'toggle on autokey' : 'toggle autokey'));
        bar.appendChild(element('div', 'tl-checkpoints', `<span class="tl-bars" id="timeline-checkpoint-bars"></span><span id="timeline-checkpoint-text"></span>`));
        // Key tools (act on the selection).
        const tools = element('div', 'tl-tools');
        const ease = document.createElement('select');
        ease.setAttribute('aria-label', 'Ease of selected keys');
        ease.innerHTML = `<option value="">Ease…</option>` + EaseCodes.map((code) => `<option value="${code.Code}">${code.Code} ${code.Label}</option>`).join('');
        ease.disabled = !state.selection.length;
        const eases = [...new Set(state.selection.map(({ Key }) => Key.Ease))];
        if (eases.length === 1) ease.value = String(eases[0]);
        ease.addEventListener('change', () => { if (ease.value !== '') app.editKeys(state.selection, { Ease: Number(ease.value) }); });
        const extrapolation = document.createElement('select');
        extrapolation.setAttribute('aria-label', 'Extrapolation of the focused track');
        extrapolation.title = 'After the last key: Hold keeps the last amount, Cycle repeats the keys, Ping-pong plays them back and forth';
        const focused = state.rows.find((row) => rowKey(row) === state.focus) || null;
        extrapolation.innerHTML = ExtrapolationCodes.map((code) => `<option value="${code.Code}">${code.Label}</option>`).join('');
        extrapolation.disabled = !focused || focused.Derived;
        if (focused) extrapolation.value = String(focused.Track.Extrapolation || 0);
        extrapolation.addEventListener('change', () => focused && app.setTrackExtrapolation(focused.Track, Number(extrapolation.value)));
        const remove = button('✕', 'Delete selected keys (Delete)', () => deleteSelection());
        remove.disabled = !state.selection.length;
        tools.append(ease, extrapolation, remove, element('span', 'tl-count', state.selection.length ? `${state.selection.length} selected` : ''));
        bar.appendChild(tools);
        bar.appendChild(button(state.open ? '▾' : '▴', state.open ? 'Collapse timeline' : 'Expand timeline', () => { state.open = !state.open; render(); }, 'tl-collapse'));
        return bar;
    }

    function renderRuler()
    {
        const row = element('div', 'tl-row tl-ruler-row');
        // The label cell of the ruler holds the view switch and the track count.
        const label = element('div', 'tl-label tl-ruler-label');
        const views = element('div', 'segmented tl-views');
        for (const [id, text, title] of [['dope', 'Keys', 'Dope sheet: keys per track'], ['curves', 'Curves', 'Curves: amount over time, tangents']])
            views.appendChild(button(text, title, () => { state.view = id; render(); }, state.view === id ? 'active' : ''));
        label.append(views, element('small', '', state.rows.length ? `${state.rows.length} track${state.rows.length === 1 ? '' : 's'}` : 'No keys yet'));
        row.appendChild(label);
        const ruler = element('div', 'tl-ruler');
        const end = span();
        const step = end <= 4 ? 0.5 : end <= 12 ? 1 : end <= 30 ? 2 : end <= 90 ? 5 : 10;
        for (let time = 0; time <= end + 1e-6; time += step)
        {
            const tick = element('span', 'tl-tick', `${Number(time.toFixed(2))}s`);
            tick.style.left = percent(time);
            ruler.appendChild(tick);
        }
        for (const time of app.checkpointSummary().Times)
        {
            const mark = element('span', 'tl-checkpoint');
            mark.style.left = percent(time);
            mark.title = `Checkpoint at ${time.toFixed(2)} s`;
            ruler.appendChild(mark);
        }
        if (app.scene.Timeline && app.scene.Timeline.Loop) ruler.appendChild(element('span', 'tl-loop-end'));
        ruler.addEventListener('pointerdown', (event) => startScrub(event));
        row.appendChild(ruler);
        return row;
    }

    function renderDopeSheet(groups)
    {
        const list = element('div', 'tl-rows');
        if (!groups.length)
        {
            list.appendChild(element('p', 'tl-empty', 'Press ◆ beside a slider in the Inspector to key it at the playhead, or turn on Auto-key and edit. Forces, emitters and particle clouds with Start / Duration timing show their Weight track here.'));
            return list;
        }
        for (const group of groups)
        {
            const collapsed = state.collapsed.has(group.Id);
            const head = element('div', 'tl-row tl-group' + (collapsed ? ' collapsed' : ''));
            const label = element('div', 'tl-label', `<span class="tl-chevron">${collapsed ? '▸' : '▾'}</span><b>${group.Title}</b><small>${group.Subtitle}</small>`);
            label.addEventListener('click', () => { if (collapsed) state.collapsed.delete(group.Id); else state.collapsed.add(group.Id); render(); });
            if (group.Node) label.addEventListener('dblclick', () => app.select(group.Node.Id));
            head.appendChild(label);
            const lane = element('div', 'tl-lane');
            const times = [...new Set(group.Rows.flatMap((row) => row.Track.Keys.map((key) => key.Time.toFixed(4))))];
            for (const time of times) { const mark = element('span', 'tl-summary'); mark.style.left = percent(Number(time)); lane.appendChild(mark); }
            lane.addEventListener('pointerdown', (event) => startScrub(event));
            head.appendChild(lane);
            list.appendChild(head);
            if (collapsed) continue;
            for (const row of group.Rows) list.appendChild(renderTrackRow(row));
        }
        return list;
    }

    function renderTrackRow(row)
    {
        const line = element('div', 'tl-row tl-track' + (rowKey(row) === state.focus ? ' focused' : '') + (row.Derived ? ' derived' : ''));
        const label = element('div', 'tl-label', `<span>${row.Label}</span>${row.Track.Extrapolation ? `<em>${ExtrapolationCodes[row.Track.Extrapolation].Label}</em>` : ''}`);
        label.title = row.Derived ? 'Generated by the timing fields (Start, Duration, Fade, Repeat). Drag a key to turn it into real keys.' : 'Click to focus (Curves view, extrapolation)';
        label.addEventListener('click', () => { state.focus = rowKey(row); render(); });
        line.appendChild(label);
        const lane = element('div', 'tl-lane');
        const keys = row.Track.Keys;
        // Segment bars between keys show the ease of each segment.
        for (let index = 0; index + 1 < keys.length; index += 1)
        {
            const bar = element('span', `tl-segment ease-${keys[index].Ease}`);
            bar.style.left = percent(previewTime(row.Track, keys[index]));
            bar.style.width = `${((previewTime(row.Track, keys[index + 1]) - previewTime(row.Track, keys[index])) / span()) * 100}%`;
            lane.appendChild(bar);
        }
        keys.forEach((key, index) =>
        {
            const diamond = element('span', 'tl-key' + (isSelected(row.Track, key) ? ' selected' : '') + ` ease-${key.Ease}`);
            diamond.style.left = percent(previewTime(row.Track, key));
            diamond.title = `${key.Time.toFixed(3)} s · ${describeAmount(key.Amount)} · ${EaseCodes[key.Ease] ? EaseCodes[key.Ease].Label : 'Linear'}`;
            diamond.setAttribute('data-key', `${rowKey(row)}#${index}`);
            diamond.addEventListener('pointerdown', (event) => startKeyDrag(event, row, index));
            lane.appendChild(diamond);
        });
        lane.addEventListener('pointerdown', (event) => { if (event.target === lane) startScrub(event); });
        line.appendChild(lane);
        return line;
    }

    function describeAmount(amount)
    {
        if (typeof amount === 'number') return Number(amount.toFixed(4)).toString();
        if (Array.isArray(amount)) return `(${amount.map((component) => Number(component.toFixed(3))).join(', ')})`;
        return String(amount);
    }

    /** A key's time including the drag preview (move or scale). */
    function previewTime(track, key)
    {
        const drag = state.drag;
        if (!drag || drag.Kind !== 'keys' || !isSelected(track, key)) return key.Time;
        if (drag.Scale !== undefined) return Math.max(0, drag.Pivot + (key.Time - drag.Pivot) * drag.Scale);
        return Math.max(0, key.Time + drag.Offset);
    }

    //------------------------------------------------------------------------------------------------------------------------
    //                                                  CURVES VIEW
    //------------------------------------------------------------------------------------------------------------------------

    function renderCurves()
    {
        const wrap = element('div', 'tl-curves');
        const row = state.rows.find((candidate) => rowKey(candidate) === state.focus);
        const side = element('div', 'tl-label tl-curve-list');
        for (const candidate of state.rows)
        {
            const item = element('button', rowKey(candidate) === state.focus ? 'active' : '', candidate.Owner ? `${candidate.Owner} › ${candidate.Label}` : candidate.Label);
            item.title = item.textContent;
            item.addEventListener('click', () => { state.focus = rowKey(candidate); render(); });
            side.appendChild(item);
        }
        if (!state.rows.length) side.appendChild(element('p', 'tl-empty', 'No tracks.'));
        wrap.appendChild(side);
        const plot = element('div', 'tl-plot');
        wrap.appendChild(plot);
        if (!row) return wrap;
        const track = row.Track;
        const sample = track.Keys[0].Amount;
        const channels = typeof sample === 'number' ? [(amount) => amount] : Array.isArray(sample) ? [0, 1, 2].map((axis) => (amount) => amount[axis]) : null;
        const svg = document.createElementNS(SvgNamespace, 'svg');
        svg.setAttribute('class', 'tl-svg');
        svg.setAttribute('preserveAspectRatio', 'none');
        plot.appendChild(svg);
        if (!channels)
        {
            plot.appendChild(element('p', 'tl-empty', `${row.Label} steps between keys (${typeof sample === 'boolean' ? 'on / off' : 'colour or choice'}); edit it in the dope sheet.`));
            return wrap;
        }
        requestAnimationFrame(() => drawCurves(svg, row, channels));
        return wrap;
    }

    function drawCurves(svg, row, channels)
    {
        const track = row.Track;
        const rect = svg.getBoundingClientRect();
        const width = Math.max(1, rect.width), height = Math.max(1, rect.height);
        svg.setAttribute('viewBox', `0 0 ${width} ${height}`);
        const end = span();
        const values = track.Keys.flatMap((key) => channels.map((channel) => channel(key.Amount)));
        const samples = [];
        for (let index = 0; index <= 200; index += 1) { const time = (index / 200) * end; const amount = sampleTrack(track, time); samples.push({ time, amount }); values.push(...channels.map((channel) => channel(amount))); }
        let low = Math.min(...values), high = Math.max(...values);
        if (high - low < 1e-6) { low -= 0.5; high += 0.5; }
        const pad = (high - low) * 0.12;
        low -= pad; high += pad;
        const x = (time) => (time / end) * width;
        const y = (amount) => height - ((amount - low) / (high - low)) * height;
        const amountAtY = (pixel) => low + ((height - pixel) / height) * (high - low);
        const colours = channels.length === 1 ? ['#f5a524'] : ['#f0535a', '#34c759', '#38bdf8'];
        const draw = (tag, attributes) => { const node = document.createElementNS(SvgNamespace, tag); for (const [name, value] of Object.entries(attributes)) node.setAttribute(name, value); svg.appendChild(node); return node; };
        for (let index = 0; index <= 4; index += 1)
        {
            const amount = low + ((high - low) * index) / 4;
            draw('line', { x1: 0, x2: width, y1: y(amount), y2: y(amount), class: 'tl-grid' });
            const text = draw('text', { x: 4, y: y(amount) - 3, class: 'tl-grid-text' }); text.textContent = Number(amount.toPrecision(3)).toString();
        }
        channels.forEach((channel, axis) => draw('polyline', { points: samples.map(({ time, amount }) => `${x(time)},${y(channel(amount))}`).join(' '), class: 'tl-curve', stroke: colours[axis] }));
        if (row.Derived) return;
        track.Keys.forEach((key, index) =>
        {
            const next = track.Keys[index + 1], previous = track.Keys[index - 1];
            if (channels.length === 1)
            {
                // Bezier handles: Out of a Bezier key towards the next key, In of the key that follows a Bezier key.
                const handle = (side) =>
                {
                    const neighbour = side === 'Out' ? next : previous;
                    const reach = Math.abs((neighbour.Time - key.Time) / 3) * (side === 'Out' ? 1 : -1);
                    const tangent = typeof key[side] === 'number' ? key[side] : 0;
                    const hx = x(key.Time + reach), hy = y(key.Amount + tangent * reach);
                    draw('line', { x1: x(key.Time), y1: y(key.Amount), x2: hx, y2: hy, class: 'tl-handle-line' });
                    const knob = draw('circle', { cx: hx, cy: hy, r: 4, class: 'tl-handle' });
                    knob.addEventListener('pointerdown', (event) =>
                    {
                        event.stopPropagation(); event.preventDefault();
                        dragWindow((move) =>
                        {
                            const local = svg.getBoundingClientRect();
                            const amount = amountAtY(move.clientY - local.top);
                            const value = (amount - key.Amount) / reach;
                            app.editKeys([{ Track: track, Key: key }], { Tangent: { [side]: Number(value.toFixed(5)) } });
                        });
                    });
                };
                if (key.Ease === 3 && next) handle('Out');
                if (previous && previous.Ease === 3) handle('In');
            }
            channels.forEach((channel, axis) =>
            {
                const dot = draw('circle', { cx: x(key.Time), cy: y(channel(key.Amount)), r: 5, class: 'tl-curve-key' + (isSelected(track, key) ? ' selected' : ''), stroke: colours[axis] });
                dot.addEventListener('pointerdown', (event) =>
                {
                    event.stopPropagation(); event.preventDefault();
                    state.selection = [{ Track: track, Key: key }];
                    const scalar = channels.length === 1;
                    const startX = event.clientX, startTime = key.Time;
                    dragWindow((move) =>
                    {
                        const local = svg.getBoundingClientRect();
                        const change = {};
                        const offset = snap(((move.clientX - startX) / Math.max(1, local.width)) * end, move.altKey);
                        if (Math.abs(offset) > 0) change.Move = { offset: startTime + offset - key.Time };
                        if (scalar) change.Amount = Number(amountAtY(move.clientY - local.top).toFixed(5));
                        if (change.Move || change.Amount !== undefined) app.editKeys([{ Track: track, Key: key }], change);
                    });
                });
            });
        });
        const head = draw('line', { x1: x(app.solver.time), x2: x(app.solver.time), y1: 0, y2: height, class: 'tl-curve-head' });
        head.setAttribute('data-time', String(app.solver.time));
    }

    //------------------------------------------------------------------------------------------------------------------------
    //                                                  INTERACTION
    //------------------------------------------------------------------------------------------------------------------------

    /** Window-level drag (the timeline re-renders while dragging, so element pointer capture would be lost). */
    function dragWindow(onMove, onEnd = () => {})
    {
        const move = (event) => onMove(event);
        const up = (event) => { window.removeEventListener('pointermove', move); window.removeEventListener('pointerup', up); onEnd(event); };
        window.addEventListener('pointermove', move);
        window.addEventListener('pointerup', up);
    }

    function startScrub(event)
    {
        if (event.button !== 0) return;
        event.preventDefault();
        host.focus({ preventScroll: true });
        if (!event.shiftKey) state.selection = [];
        app.seek(snap(timeAtClientX(event.clientX), event.altKey));
        dragWindow((move) => app.seek(snap(timeAtClientX(move.clientX), move.altKey)));
    }

    function startKeyDrag(event, row, index)
    {
        if (event.button !== 0) return;
        event.preventDefault();
        event.stopPropagation();
        host.focus({ preventScroll: true });
        let track = row.Track;
        if (row.Derived)
        {
            // Generated timing keys become real Weight keys the moment one is touched.
            track = app.materialiseWeight(row.Node);
            app.invalidateCheckpoints(0);
        }
        const key = track.Keys[index];
        if (!key) return;
        state.focus = rowKey(row);
        if (event.shiftKey) state.selection = isSelected(track, key) ? state.selection.filter((entry) => !(entry.Track === track && entry.Key === key)) : [...state.selection, { Track: track, Key: key }];
        else if (!isSelected(track, key)) state.selection = [{ Track: track, Key: key }];
        const startX = event.clientX;
        const scaling = event.ctrlKey || event.metaKey;
        const pivot = app.solver.time;
        state.drag = { Kind: 'keys', Offset: 0, ...(scaling ? { Scale: 1, Pivot: pivot } : {}) };
        render();
        dragWindow((move) =>
        {
            const rect = laneRect();
            const delta = ((move.clientX - startX) / Math.max(1, rect.width)) * span();
            if (scaling)
            {
                const from = key.Time - pivot;
                state.drag.Scale = Math.abs(from) > 1e-6 ? Math.max(0, (from + delta) / from) : 1;
            }
            else state.drag.Offset = snap(delta, move.altKey);
            render();
        }, () =>
        {
            const drag = state.drag;
            state.drag = null;
            if (drag.Scale !== undefined && Math.abs(drag.Scale - 1) > 1e-6) app.editKeys(state.selection, { Move: { scale: drag.Scale, pivot: drag.Pivot } });
            else if (Math.abs(drag.Offset) > 1e-9) app.editKeys(state.selection, { Move: { offset: drag.Offset } });
            else { app.notify(); }
        });
    }

    function deleteSelection()
    {
        if (!state.selection.length) return;
        const selection = state.selection;
        state.selection = [];
        app.editKeys(selection, { Delete: true });
    }

    host.addEventListener('keydown', (event) =>
    {
        if (event.target && (event.target.tagName === 'INPUT' || event.target.tagName === 'SELECT')) return;
        if ((event.key === 'Delete' || event.key === 'Backspace') && state.selection.length > 0) { event.preventDefault(); event.stopPropagation(); deleteSelection(); }
        else if (event.key === 'Home') { event.preventDefault(); event.stopPropagation(); app.goToStart(); }
        else if (event.key === 'End') { event.preventDefault(); event.stopPropagation(); app.goToEnd(); }
        else if (event.key === ',') { event.stopPropagation(); app.stepBack(); }
        else if (event.key === '.') { event.stopPropagation(); app.stepOnce(); }
        else if (event.key === 'a' && (event.ctrlKey || event.metaKey)) { event.preventDefault(); state.selection = state.rows.filter((row) => !row.Derived).flatMap((row) => row.Track.Keys.map((key) => ({ Track: row.Track, Key: key }))); render(); }
    });

    //------------------------------------------------------------------------------------------------------------------------
    //                                                  PER-FRAME UPDATE
    //------------------------------------------------------------------------------------------------------------------------

    function update()
    {
        if (!app.scene || !app.solver) return;
        const time = app.solver.time;
        const readout = host.querySelector('#timeline-time');
        if (readout) readout.textContent = formatTimecode(time);
        const playhead = host.querySelector('.tl-playhead');
        if (playhead)
        {
            const ruler = host.querySelector('.tl-ruler');
            const body = host.querySelector('.tl-body');
            if (ruler && body)
            {
                const offset = ruler.getBoundingClientRect().left - body.getBoundingClientRect().left;
                playhead.style.left = `${offset + Math.min(1, time / span()) * ruler.getBoundingClientRect().width}px`;
                playhead.classList.toggle('past-end', time > span());
            }
        }
        const head = host.querySelector('.tl-curve-head');
        if (head)
        {
            const svg = head.ownerSVGElement;
            const width = svg && svg.viewBox && svg.viewBox.baseVal ? svg.viewBox.baseVal.width : 0;
            const x = Math.min(1, time / span()) * width;
            head.setAttribute('x1', x); head.setAttribute('x2', x);
        }
        const summary = app.checkpointSummary();
        const bars = host.querySelector('#timeline-checkpoint-bars');
        if (bars)
        {
            // Bars = how much of the timeline (0 → End) is covered by checkpoints, within what the budget can hold.
            const shown = 6;
            const wanted = Math.max(1, Math.min(summary.Capacity || 1, Math.floor(app.timeline().End / (summary.Interval || 0.5))));
            const filled = Math.min(shown, Math.round((Math.min(summary.Count, wanted) / wanted) * shown));
            bars.textContent = '▮'.repeat(filled) + '▯'.repeat(shown - filled);
            const text = host.querySelector('#timeline-checkpoint-text');
            if (text) text.textContent = `${summary.Count} cached`;
            if (bars.parentElement) bars.parentElement.title = `Checkpoints: ${summary.Count} of ${summary.Capacity} (${(summary.Bytes / 1048576).toFixed(0)} MB). One checkpoint every ${summary.Interval} s of simulation, ${(summary.BytesEach / 1048576).toFixed(1)} MB each; the oldest is dropped first. Scrubbing back restores the newest checkpoint before the playhead and re-steps.`;
        }
    }

    return { render, update, state };
}
