//============================================================================================================================================
//                                                    GENERATELAYERSPECIFICATIONS.MJS
//============================================================================================================================================
// 🧩 Engine/LayerSpecifications.toml → Engine/LayerSpecifications.js (browser). Run after editing the TOML:
//     node GenerateLayerSpecifications.mjs
// Refuses to write when the specification breaks a rule. FluidValidation.mjs fails when the generated file is out of date.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseToml } from './Engine/TomlSubset.js';
import { validateLayerSpecifications, specificationHash } from './Engine/LayerSpecificationValidation.js';

const Folder = path.dirname(fileURLToPath(import.meta.url));
export const SpecificationSource = path.join(Folder, 'Engine', 'LayerSpecifications.toml');
export const SpecificationOutput = path.join(Folder, 'Engine', 'LayerSpecifications.js');

export function generateLayerSpecifications(text)
{
    const document = parseToml(text);
    const problems = validateLayerSpecifications(document);
    if (problems.length) throw new Error('LayerSpecifications.toml is invalid:\n  ' + problems.join('\n  '));
    const hash = specificationHash(document);
    return [
        '//============================================================================================================================================',
        '//                                                         LAYERSPECIFICATIONS.JS',
        '//============================================================================================================================================',
        '// 📝 Generated by GenerateLayerSpecifications.mjs from Engine/LayerSpecifications.toml. Edit the TOML, never this file.',
        '',
        `export const SpecificationHash = '${hash}';`,
        `export const LayerSpecificationDocument = Object.freeze(${JSON.stringify(document, null, 4)});`,
        '',
    ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
{
    const output = generateLayerSpecifications(fs.readFileSync(SpecificationSource, 'utf8'));
    fs.writeFileSync(SpecificationOutput, output);
    console.log(`Wrote ${path.relative(Folder, SpecificationOutput)} · hash ${output.match(/SpecificationHash = '([0-9a-f]+)'/)[1]}`);
}
