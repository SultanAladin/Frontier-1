// JSDOM_DIR=/tmp/smoke node Experimental/ComponentViewer/Scripts/SmokeAssetViewer.mjs
// Exercises the third page's placeholder parenting and asset assignment; WebGL is mocked.
import { pathToFileURL, fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { bootStudio } from '../../Shared/Studio/Scripts/StudioHarness.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..') + '/';
const { w, $, click, sleep, step, finish } = bootStudio({ htmlPath: root + 'AssetViewer.html', url: 'http://localhost:8096/Experimental/ComponentViewer/AssetViewer.html' });
await import(pathToFileURL(root + 'AssetViewerMain.js'));
const { viewer, assets } = w.FrontierComponentViewer;
const add = (label) => {
  click($('AddComponentBtn'));
  const button = [...$('AddList').querySelectorAll('.menu-item')].find((b) => b.textContent.includes(label));
  click(button);
};
await step('empty start and parented placeholders', async () => {
  if (viewer.blueprint.components.length !== 1 || assets.size) throw Error('Expected an empty blueprint and content');
  click($('AddComponentBtn'));
  const menu = $('AddList').textContent;
  for (const wanted of ['Instance', 'Fixed socket', 'Point Light', 'Spot Light']) if (!menu.includes(wanted)) throw Error(`Missing ${wanted} in add palette`);
  for (const unwanted of ['Camera', 'Collision', 'Vehicle Movement', 'Static Mesh']) if (menu.includes(unwanted)) throw Error(`Unexpected ${unwanted} in add palette`);
  $('AddSearch').value = 'hinge'; $('AddSearch').dispatchEvent(new w.Event('input', { bubbles: true }));
  if ($('AddList').querySelectorAll('.menu-item').length !== 1 || !$('AddList').textContent.includes('Hinge socket')) throw Error('Add palette search failed');
  click($('AddComponentBtn'));
  add('Point Light');
  const camera = viewer.blueprint.components.find((c) => c.type === 'PointLight');
  add('Instance');
  const placeholder = viewer.blueprint.components.find((c) => c.name === 'Instance');
  if (!placeholder || placeholder.parent !== camera.id || placeholder.props.asset) throw Error('Placeholder is not empty under camera');
  add('Fixed socket');
  const socket = viewer.blueprint.components.find((c) => c.type === 'Socket');
  add('Instance');
  const second = viewer.blueprint.components.find((c) => c.name === 'Instance1');
  if (second.parent !== socket.id || second.props.asset) throw Error('Placeholder not attached to socket');
  const sections = [...$('Details').querySelectorAll('.section-head')].map((x) => x.textContent.trim());
  if (sections.join(',') !== 'TRANSFORM,STATIC MESH') throw Error('Placeholder has extra details: ' + sections.join(','));
});
const obj = new TextEncoder().encode('v 0 0 0\nv 1 0 0\nv 0 1 0\nf 1 2 3\n');
const file = { name: 'triangle.obj', size: obj.length, arrayBuffer: async () => obj.buffer };
await step('import file into selected placeholder', async () => {
  const input = $('Details').querySelector('input[type=file]');
  if (!input) throw Error('Details file input missing');
  Object.defineProperty(input, 'files', { value: [file], configurable: true });
  input.dispatchEvent(new w.Event('change', { bubbles: true }));
  for (let i = 0; i < 100 && !assets.size; i++) await sleep(10);
  const c = viewer.blueprint.components.find((x) => x.name === 'Instance1');
  const asset = assets.get(c.props.asset);
  if (!asset?.out.geometry || asset.steps.uv.state === 'done') throw Error('Import not assigned, or unexpectedly baked');
  const sections = [...$('Details').querySelectorAll('.section-head')].map((x) => x.textContent.trim());
  if (!sections.includes('TRANSFORM') || !sections.includes('STATIC MESH')) throw Error('Assigned mesh details missing: ' + sections);
  for (const label of ['RENDERING', 'TAGS', 'Collision preset', 'Cast shadow']) if ($('Details').textContent.includes(label)) throw Error('Unexpected inspector field: ' + label);
  if ($('Details').querySelector('input[type=file]') || $('Details').textContent.includes('Import from file')) throw Error('File import must disappear after assignment');
});
await step('assign from Content via drop', async () => {
  const first = viewer.blueprint.components.find((c) => c.name === 'Instance');
  const row = [...$('ComponentTree').querySelectorAll('.comp-row')].find((r) => r.textContent.includes('Instance') && !r.textContent.includes('Instance1'));
  click(row);
  click($('DrawerHandle'));
  if (!$('DrawerBody').querySelector('[draggable=true]')) throw Error('Browser asset missing');
  const drop = $('Details').querySelector('.asset-drop');
  const event = new w.Event('drop', { bubbles: true, cancelable: true });
  Object.defineProperty(event, 'dataTransfer', { value: { getData: () => [...assets.keys()][0], files: [] } });
  drop.dispatchEvent(event);
  if (first.props.asset !== [...assets.keys()][0]) throw Error('Content drop failed');
  if (!$('Details').querySelector('.world-material-container') || $('Details').querySelector('input[type=file]')) throw Error('Dropped asset details did not update');
});
await step('World Mirror browser and preset drop', async () => {
  if (!$('Drawer').classList.contains('open')) click($('DrawerHandle'));
  const cards = [...$('DrawerBody').querySelectorAll('.browser-asset')];
  if (!cards.some((c) => c.textContent.includes('Calibration Cube')) || cards.length < 10) throw Error('World Mirror catalog missing');
  $('AssetBrowserSearch').value = 'Calibration Cube';
  $('AssetBrowserSearch').dispatchEvent(new w.Event('input', { bubbles: true }));
  if ($('DrawerBody').querySelectorAll('.browser-asset').length !== 1) throw Error('Browser search failed');
  const card = $('DrawerBody').querySelector('.browser-asset');
  const transfer = { data: {}, effectAllowed: '', setData(k,v) { this.data[k] = v; }, getData(k) { return this.data[k] || ''; }, files: [] };
  const drag = new w.Event('dragstart', { bubbles: true }); Object.defineProperty(drag, 'dataTransfer', { value: transfer }); card.dispatchEvent(drag);
  const drop = new w.Event('drop', { bubbles: true, cancelable: true }); Object.defineProperty(drop, 'dataTransfer', { value: transfer });
  $('Details').querySelector('.asset-drop').dispatchEvent(drop);
  const c = viewer.blueprint.components.find((x) => x.name === 'Instance');
  for (let i = 0; i < 100 && assets.get(c.props.asset)?.origin !== 'world-mirror'; i++) await sleep(10);
  if (assets.get(c.props.asset)?.name !== 'Calibration Cube') throw Error('World Mirror model not assigned');
});
await step('World Mirror multipart model', async () => {
  const { makeWorldModel, worldModels } = await import(pathToFileURL(root + 'WorldMirrorAssets.js'));
  const model = worldModels.find((m) => m.PropId === 'tire_stack');
  const asset = await makeWorldModel(model.Id, {});
  if (!asset.out.geometry || !asset.palette || asset.palette.length < 2) throw Error('Multipart model not converted');
});
await step('inspector editors and real bake previews', async () => {
  const c = viewer.blueprint.components.find((x) => x.name === 'Instance');
  const asset = assets.get(c.props.asset);
  if (w.document.querySelector('[data-left=content]')) throw Error('Content tab still present');
  click($('Details').querySelector('[data-inspect=uv]'));
  if ($('UvWorkspace').hidden || !$('Studio').hidden) throw Error('Studio UV workspace did not open');
  click($('CompilerPack')); click($('CompilerClose'));
  if (asset.steps.uv.state !== 'done' || !asset.out.uv) throw Error('UV workspace did not save the layout');
  click($('Details').querySelector('[data-inspect=sdf]'));
  if ($('SdfWorkspace').hidden || !$('Studio').hidden) throw Error('Studio SDF workspace did not open');
  for (let i = 0; i < 600 && asset.steps.sdf.state !== 'done'; i++) await sleep(10);
  if (asset.steps.sdf.state !== 'done' || !asset.sparseSdf) throw Error('SDF workspace failed to bake');
  click($('SdfWsClose'));
  const axis = $('Details').querySelector('[aria-label="SDF slice axis"]');
  if (!axis || ![...axis.querySelectorAll('button')].some((b) => b.textContent === 'X')) throw Error('Studio SDF axis controls missing');
  click([...axis.querySelectorAll('button')].find((b) => b.textContent === 'X'));
  const depth = $('Details').querySelector('input[aria-label="Slice depth"]'); depth.value = '0.7'; depth.dispatchEvent(new w.Event('input', { bubbles: true }));
  if (!$('Details').textContent.includes('X 70%')) throw Error('SDF slice depth did not update');
  if (!$('Details').textContent.includes('Islands · seams') || !$('Details').textContent.includes('Sparse bricks')) throw Error('Studio inspector stats missing');
  // The inspector bake remains available even when the WebGL2 workspace cannot be created in jsdom.
  const lodButton = [...$('Details').querySelectorAll('button')].find((b) => b.textContent === 'Build clusters' || b.textContent === 'Rebuild clusters');
  if (!lodButton) throw Error('LOD inspector bake missing');
  click(lodButton);
  for (let i = 0; i < 600 && asset.steps.lod.state !== 'done' && asset.steps.lod.state !== 'error'; i++) await sleep(10);
  if (asset.steps.lod.state !== 'done') throw Error(`lod failed: ${asset.steps.lod.error}`);
  if ($('Details').textContent.includes('Forced LOD') || $('Details').textContent.includes('Simulate physics')) throw Error('Removed mesh controls still visible');
  const levelSlider = $('Details').querySelector('[aria-label="Preview LOD level"]');
  const thumbnail = $('Details').querySelector('[aria-label="Cluster LOD mesh preview"]');
  if (!levelSlider || !thumbnail || levelSlider.disabled || +levelSlider.max !== asset.out.lod.levels.length - 1) throw Error('Cluster preview or level slider missing');
  const priorLod = c.props.lod;
  levelSlider.value = levelSlider.max; levelSlider.dispatchEvent(new w.Event('input', { bubbles: true }));
  if (c.props.lod !== priorLod || !$('Details').textContent.includes(`LOD ${levelSlider.max}`)) throw Error('LOD preview changed component property or failed to update');
  if (!$('Legend').textContent.includes('Cluster colours')) throw Error('LOD slider did not activate the viewport preview');
  const workspace = $('ClusterWorkspace');
  for (const mode of ['clusters', 'groups', 'levels', 'triangles', 'budget']) if (!workspace.querySelector(`[data-mode=${mode}]`)) throw Error(`Missing debug mode ${mode}`);
  if (workspace.querySelector('[data-inspect]')) throw Error('Unrelated inspector controls in LOD workspace');
  const capture = [...$('Details').querySelectorAll('button')].find((b) => b.textContent === 'Capture'); click(capture);
  for (let i = 0; i < 200 && !$('Details').textContent.includes('Captured · not yet saved'); i++) await sleep(10);
  click([...$('Details').querySelectorAll('button')].find((b) => b.textContent === 'Save as icon'));
  if (!asset.out.uv || !asset.sparseSdf || !asset.out.lod || !asset.out.icon) throw Error('Bake outputs missing');
  click($('Details').querySelector('[data-inspect=geometry]'));
  if ($('GeometryEditor').hidden || !$('Studio').hidden) throw Error('Studio geometry workspace did not open');
  const slider = $('GeoScaleX'); slider.value = '1.5'; slider.dispatchEvent(new w.Event('input', { bubbles: true }));
  click($('GeoApply'));
  for (let i = 0; i < 200 && asset.steps.geometry.state !== 'done'; i++) await sleep(10);
  if (asset.settings.geometry.scale[0] !== 1.5 || asset.steps.uv.state !== 'stale') throw Error('Geometry update/invalidation failed');
  if (!$('GeometryEditor').hidden || $('Studio').hidden) throw Error('Geometry workspace failed to close');
  for (let i = 0; i < 500 && !$('Details').querySelector('.material-panel'); i++) await sleep(10);
  if (!$('Details').querySelector('.material-panel')) throw Error('World Mirror material card failed: ' + $('Details').querySelector('.world-material-container')?.textContent);
  if (!$('Details').querySelector('[data-material-channel=roughness]') || !$('Details').textContent.includes('Material channels')) throw Error('Original material channel UI missing');
  click($('Details').querySelector('[data-material-channel=roughness]'));
  await sleep(20);
  if (!$('Details').querySelector('[aria-label="Roughness source"]')) throw Error('Material source editor missing');
  const type = $('Details').querySelector('select[aria-label="Material type"]'); type.value = 'Metal'; type.dispatchEvent(new w.Event('change', { bubbles: true })); await sleep(20);
  if (Object.values(c.props.materialEdits)[0]?.Type !== 'Metal') throw Error('World Mirror material edits did not reach component');
  click($('Details').querySelector('[data-inspect=fracture]'));
  click([...$('Details').querySelectorAll('button')].find((b) => b.textContent.includes('Generate fracture preview')));
  if (!c.props.fracturePreview?.cells.length || !$('Details').querySelector('canvas')) throw Error('Fracture preview not generated');
});
await step('authored OBJ UVs appear immediately and survive geometry changes', async () => {
  add('Instance');
  const c = viewer.blueprint.components.find((x) => x.name === 'Instance2');
  const bytes = new TextEncoder().encode('v 0 0 0\nv 1 0 0\nv 0 1 0\nvt 0 0\nvt 1 0\nvt 0 1\nf 1/1 2/2 3/3\n');
  const input = $('Details').querySelector('input[type=file]');
  Object.defineProperty(input, 'files', { value: [{ name: 'with_uv.obj', size: bytes.length, arrayBuffer: async () => bytes.buffer }], configurable: true });
  input.dispatchEvent(new w.Event('change', { bubbles: true }));
  for (let i = 0; i < 200 && !c.props.asset; i++) await sleep(10);
  const asset = assets.get(c.props.asset);
  if (!asset?.out.uv?.authored || asset.steps.uv.state !== 'done' || !$('Details').textContent.includes('Authored UVs')) throw Error('Authored UVs not shown');
  click($('Details').querySelector('[data-inspect=geometry]'));
  click($('GeoMirrorX')); click($('GeoApply'));
  for (let i = 0; i < 200 && asset.steps.geometry.state !== 'done'; i++) await sleep(10);
  if (asset.steps.uv.state !== 'done' || !asset.out.uv.authored || asset.out.uv.uvs[2] !== 0 || asset.out.uv.uvs[3] !== 1) throw Error('Authored UV winding not preserved');
});
await finish();
